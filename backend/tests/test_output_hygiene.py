def test_a_download_is_named_after_the_document_not_the_workspace(app_client, two_documents):
    token, ids, document_type = two_documents
    doc_id, version_id = ids[0]
    got = app_client.get(f"/api/v1/document-versions/{version_id}/download",
                         headers=_auth(token))
    assert got.status_code == 200, got.text
    header = got.headers["content-disposition"]
    assert "Secret Workspace Name" not in header and "81000" not in header
    assert f"{doc_id[:8]}.docx" in header
    assert safe_filename(document_type) in header

    link = app_client.post(f"/api/v1/document-versions/{version_id}/download-url",
                           headers=_auth(token)).json()
    assert link["filename"].endswith(f"{doc_id[:8]}.docx")
    fetched = app_client.get(link["url"])
    assert fetched.status_code == 200, fetched.text
    assert f"{doc_id[:8]}.docx" in fetched.headers["content-disposition"]


def test_a_bulk_archive_has_neutral_headers_and_distinct_names(app_client, two_documents):
    token, ids, _type = two_documents
    first = ids[0][0]
    got = app_client.post("/api/v1/documents:download", headers=_auth(token),
                          json={"document_ids": [first, first, ids[1][0]]})
    assert got.status_code == 200, got.text
    with zipfile.ZipFile(io.BytesIO(got.content)) as archive:
        infos = archive.infolist()
        names = [i.filename for i in infos]
        assert len(set(names)) == len(names) == 3
        assert not any("Secret Workspace" in n for n in names)
        for info in infos:
            assert info.date_time == FIXED_ZIP_TIMESTAMP
            # A constant, never the source file's permissions.
            assert info.external_attr == 0o600 << 16 and info.create_system == 0


