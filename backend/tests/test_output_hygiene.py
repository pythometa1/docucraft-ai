"""What a delivered document says about how it was made: nothing.

Every test here produces a real output through the product's own code -- emit,
the HTML assembly, the fill engine, the PDF converter, the spreadsheet builder,
the download endpoints -- and then opens the package and reads what a recipient
could read: the core and extended properties, the parts in the archive, the
settings, the PDF information dictionary, the file name and the zip headers.

The things that must not be there: the generator library, the converter and its
build, the server's time zone, the product's name, internal ids and project
names, drafting labels and retrieval citation markers.
"""

