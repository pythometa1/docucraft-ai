def test_a_file_is_named_after_the_document():
    stamp = datetime(2026, 9, 19, 22, 30)
    doc_id = "3f9a1c2b-1111-4222-8333-444455556666"
    assert document_filename(document_type="Offer Letter", created_at=stamp,
                             document_id=doc_id, language="en", ext="docx") == \
        "Offer Letter - 2026-09-19 - 3f9a1c2b.docx"
    assert document_filename(document_type=None, created_at=stamp, document_id=doc_id,
                             language="English", ext="pdf") == \
        "Document - 2026-09-19 - 3f9a1c2b.pdf"
    assert document_filename(document_type="Offer/Letter", created_at=stamp,
                             document_id=doc_id, language="zh-CN", ext="docx") == \
        "Offer Letter - 2026-09-19 - 3f9a1c2b - zh-CN.docx"
    # A missing clock falls back to now, in UTC.
    assert re.match(r"Document - \d{4}-\d{2}-\d{2} - 00000000\.docx",
                    document_filename(document_type="", created_at=None, document_id="",
                                      language=None, ext=".docx"))


def test_names_are_safe_and_unique():
    assert safe_filename('CTD Module 3.2.A / 3.2.R: "x"?.docx') == \
        "CTD Module 3.2.A 3.2.R x.docx"
    assert safe_filename("...") == "Document"
    assert safe_filename("Module 3.2.P") == "Module 3.2.P"
    taken: set = set()
    assert [unique_name("a.docx", taken) for _ in range(3)] == \
        ["a.docx", "a (2).docx", "a (3).docx"]
    assert unique_name("README", {"README"}) == "README (2)"


def test_content_disposition_encodes_everything():
    header = content_disposition("Module 3.2.A / 3.2.R.docx")
    assert "/" not in header.split("filename*=")[1]
    assert header.startswith('attachment; filename="Module 3.2.A 3.2.R.docx"')
    wide = content_disposition("录用通知 - 2026-09-19 - 3f9a1c2b.pdf")
    assert 'filename="2026-09-19 - 3f9a1c2b.pdf"' in wide
    assert "%E5%BD%95" in wide
    assert 'filename="download.pdf"' in content_disposition("录用通知.pdf")


