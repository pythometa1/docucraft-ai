def test_the_static_region_gate_forgives_the_scrub_and_nothing_more(tmp_path):
    from app.qa.layout_integrity import docprops_failures

    def package(name, core):
        path = tmp_path / name
        with zipfile.ZipFile(path, "w") as archive:
            archive.writestr("docProps/core.xml", core)
        return str(path)

    template = package("t.docx", CORE)
    scrubbed = package("o.docx", normalise_core_properties(CORE))
    assert docprops_failures(template, scrubbed) == []
    retitled = package("r.docx", normalise_core_properties(
        CORE.replace(b"Offer of employment", b"Something else")))
    assert docprops_failures(template, retitled)


def test_a_filled_letter_carries_no_template_bookkeeping_and_passes_its_gate(
        fixtures_dir, tmp_path):
    """The fill path edits the customer's own package; its core properties are
    scrubbed on the way out and the static-region gate still passes."""
    from app.compiler.rule_compiler import compile_manifest
    from app.generation.docx_renderer import fill_template
    from app.generation.source_ingestion import extract_records
    from app.generation.source_resolver import apply_binding, suggest_bindings
    from app.qa.layout_integrity import structural_failures
    from app.templates.parsers.docx_prescan import prescan

    original = fixtures_dir / "templates" / "hospira_offer.docx"
    if not original.exists():
        pytest.skip("client template master not present")
    # The master, with the bookkeeping a real one carries written into it.
    template = tmp_path / "template.docx"
    with zipfile.ZipFile(original) as src, zipfile.ZipFile(template, "w") as out:
        for info in src.infolist():
            data = src.read(info.filename)
            if info.filename == "docProps/core.xml":
                data = CORE
            out.writestr(info, data)

    compiled = compile_manifest(prescan(str(template)))
    manifest = {"fields": compiled.fields, "conditions": compiled.conditions,
                "blocks": compiled.blocks, "delete_always": compiled.delete_always}
    columns, records = extract_records(
        str(fixtures_dir / "records" / "colleagues.xlsx"), "xlsx")
    bindings = suggest_bindings(manifest, columns).as_field_bindings()
    out = tmp_path / "letter.docx"
    result = fill_template(str(template), str(out), manifest,
                           apply_binding(records[0], bindings), locale="en_AU")

    core = _parts(out)["docProps/core.xml"].decode()
    assert "HR-TPL-ANZ-014" not in core and "Talent Ops" not in core
    assert "<cp:revision>1</cp:revision>" in core
    assert "Priya Sharma" in core
    assert structural_failures(str(template), str(out)) == []
    assert not any("core.xml" in note for note in result.qa_notes), result.qa_notes


