def _toolchain_pdf(path):
    from pypdf import PdfWriter
    from pypdf.generic import DecodedStreamObject, NameObject

    writer = PdfWriter()
    writer.add_blank_page(200, 200)
    writer.add_metadata({"/Producer": "LibreOffice 26.8.0.3 (AARCH64)", "/Creator": "Writer",
                         "/Author": "python-docx",
                         "/CreationDate": "D:20260919140218+05'30'"})
    xmp = DecodedStreamObject()
    xmp.set_data(b"<x:xmpmeta>LibreOffice Writer python-docx +05:30</x:xmpmeta>")
    xmp[NameObject("/Type")] = NameObject("/Metadata")
    writer._root_object[NameObject("/Metadata")] = writer._add_object(xmp)
    writer.write(str(path))


@pytest.mark.parametrize("with_source", [True, False])
def test_pdf_metadata_describes_the_document_not_the_converter(tmp_path, with_source):
    from pypdf import PdfReader

    from app.generation.pdf_renderer import scrub_pdf_metadata

    pdf = tmp_path / "out.pdf"
    _toolchain_pdf(pdf)
    source = None
    if with_source:
        document = base_docx.new_document()
        document.core_properties.title = "Offer of employment"
        document.core_properties.author = "Acme HR"
        source = tmp_path / "src.docx"
        document.save(str(source))
    scrub_pdf_metadata(pdf, source)

    raw = pdf.read_bytes()
    for word in (b"LibreOffice", b"Writer", b"python-docx", b"+05", b"xmpmeta"):
        assert word not in raw, word
    reader = PdfReader(str(pdf))
    assert "/Metadata" not in reader.trailer["/Root"]
    meta = dict(reader.metadata or {})
    if with_source:
        assert meta == {"/Title": "Offer of employment", "/Author": "Acme HR"}
    else:
        assert meta == {}
    assert not (tmp_path / "out.pdf.scrubbing").exists()


