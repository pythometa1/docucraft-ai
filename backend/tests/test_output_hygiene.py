TOOLCHAIN = ("python-docx", "openpyxl", "Openpyxl", "LibreOffice", "DocuMind",
             "Microsoft Macintosh Word", "Normal.dotm", "generated by")


def _auth(token):
    return {"Authorization": f"Bearer {token}"}


def _parts(path) -> dict:
    with zipfile.ZipFile(path if isinstance(path, io.BytesIO) else str(path)) as archive:
        return {name: archive.read(name) for name in archive.namelist()}


def _assert_neutral_package(path):
    parts = _parts(path)
    names = set(parts)
    assert not any(n.startswith("customXml/") for n in names), sorted(names)
    assert "docProps/thumbnail.jpeg" not in names
    core = parts["docProps/core.xml"].decode()
    app = parts.get("docProps/app.xml", b"").decode()
    for word in TOOLCHAIN:
        assert word not in core and word not in app, word
    assert "<Application>" not in app and "<Template>" not in app
    settings = parts["word/settings.xml"].decode()
    assert "w:rsids" not in settings and "w14:docId" not in settings
    assert b"thumbnail" not in parts["_rels/.rels"]
    assert b"customXml" not in parts["[Content_Types].xml"]
    assert normalisation_failures(str(path)) == []
    return parts


