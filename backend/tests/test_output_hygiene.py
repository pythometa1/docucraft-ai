def test_a_changed_default_template_fails_the_build_loudly(tmp_path):
    source = tmp_path / "odd.docx"
    with zipfile.ZipFile(base_docx._default_template()) as src, \
            zipfile.ZipFile(source, "w") as out:
        for info in src.infolist():
            if info.filename != "docProps/thumbnail.jpeg":
                out.writestr(info, src.read(info.filename))
    with pytest.raises(base_docx.BaseTemplateChanged):
        base_docx.build(str(tmp_path / "x.docx"), str(source))

    reshaped = tmp_path / "reshaped.docx"
    with zipfile.ZipFile(base_docx._default_template()) as src, \
            zipfile.ZipFile(reshaped, "w") as out:
        for info in src.infolist():
            data = src.read(info.filename)
            if info.filename == "word/settings.xml":
                data = data.replace(b"<w:savePreviewPicture/>", b"")
            out.writestr(info, data)
    with pytest.raises(base_docx.BaseTemplateChanged):
        base_docx.build(str(tmp_path / "y.docx"), str(reshaped))


